"""Generate a two-channel optical phantom and sample its line profile (requires Pillow)."""

import json
import math
import random
from pathlib import Path

from PIL import Image, ImageChops, ImageDraw, ImageFilter, ImageOps

ROOT = Path(__file__).resolve().parent
FIELD = (880, 555)
ROI = (530, 116, 750, 366)
PROFILE_ROW = 132
PIXEL_UM = 0.5


def make_channels() -> tuple[Image.Image, Image.Image]:
    rng = random.Random(2269)
    channels = (Image.new("L", FIELD), Image.new("L", FIELD))
    particles = [
        (rng.randrange(20, 860), rng.randrange(20, 535), rng.randrange(13, 28))
        for _ in range(55)
    ]
    particles += [(585, 248, 27), (650, 259, 23), (702, 225, 29)]
    for x, y, radius in particles:
        width = radius * rng.uniform(0.78, 1.26)
        height = radius * rng.uniform(0.74, 1.16)
        strong_channel = rng.randrange(2)
        for index, channel in enumerate(channels):
            canvas = ImageDraw.Draw(channel)
            if index == strong_channel:
                canvas.ellipse((x - width, y - height, x + width, y + height),
                               outline=rng.randrange(105, 186), width=rng.randrange(3, 6))
            # An offset inner signal, with both channels sharing the same coordinate system.
            center_x = x + rng.uniform(-0.29, 0.29) * radius
            center_y = y + rng.uniform(-0.28, 0.28) * radius
            spot = radius * rng.uniform(0.22, 0.41)
            canvas.ellipse((center_x - spot, center_y - spot, center_x + spot, center_y + spot),
                           fill=rng.randrange(80, 140))
            for _ in range(rng.randrange(7, 13)):
                angle = rng.random() * math.tau
                distance = rng.uniform(0.15, 0.94)
                px = x + math.cos(angle) * distance * width
                py = y + math.sin(angle) * distance * height
                size = rng.uniform(0.8, 2.3)
                canvas.ellipse((px - size, py - size, px + size, py + size),
                               fill=rng.randrange(45, 152))

    def blur_signal(channel: Image.Image) -> Image.Image:
        """Combine the sharp signal and its softer halo."""
        core = channel.filter(ImageFilter.GaussianBlur(1.6))
        halo = channel.filter(ImageFilter.GaussianBlur(5.8))
        return ImageChops.add(core, halo)

    return blur_signal(channels[0]), blur_signal(channels[1])


def main() -> None:
    cyan, magenta = make_channels()
    background = Image.new("RGB", FIELD, (8, 14, 34))
    tint_cyan = ImageOps.colorize(cyan, (0, 0, 0), (59, 246, 208))
    tint_magenta = ImageOps.colorize(magenta, (0, 0, 0), (244, 78, 180))
    merged = ImageChops.add(background, ImageChops.add(tint_cyan, tint_magenta))
    merged.save(ROOT / "phantom.png", optimize=True)
    merged.crop(ROI).save(ROOT / "inset.png", optimize=True)

    left, top, right, _ = ROI
    row = top + PROFILE_ROW
    profile = []
    for x in range(left, right):
        values = [
            round(sum(channel.getpixel((x, y)) for y in range(row - 4, row + 5)) / 9 / 255, 4)
            for channel in (cyan, magenta)
        ]
        profile.append([(x - left + 0.5) * PIXEL_UM, *values])
    series = ",\n".join(f"  {json.dumps(sample)}" for sample in profile)
    (ROOT / "profile.js").write_text(
        "// Generated by build_phantom.py. Columns: distance (μm), cyan, magenta.\n"
        f"const phantomProfile = [\n{series}\n];\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
